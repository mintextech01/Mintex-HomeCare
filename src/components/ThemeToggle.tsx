import { useTheme } from "@/contexts/ThemeContext";

/**
 * Sun/moon theme toggle button.
 * Works on all screen sizes — renders inline in the header.
 */
/** compact: a small version for the desktop utility bar. */
const ThemeToggle = ({ compact = false }: { compact?: boolean }) => {
  const { isDark, toggleTheme } = useTheme();

  return (
    <button
      onClick={toggleTheme}
      aria-label={isDark ? "Switch to light mode" : "Switch to dark mode"}
      className={`relative flex items-center justify-center rounded-full border border-border bg-background transition-all duration-300 focus:outline-none focus-visible:ring-2 focus-visible:ring-primary ${
        compact ? "w-7 h-7 [&>svg]:!w-[15px] [&>svg]:!h-[15px]" : "w-11 h-11"
      }`}
    >
      {isDark ? (
        /* Moon icon */
        <svg
          xmlns="http://www.w3.org/2000/svg"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth={2}
          strokeLinecap="round"
          strokeLinejoin="round"
          className="w-[18px] h-[18px] absolute"
          style={{ color: "#60a5fa" }}
        >
          <path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z" />
        </svg>
      ) : (
        /* Sun icon */
        <svg
          xmlns="http://www.w3.org/2000/svg"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth={2}
          strokeLinecap="round"
          strokeLinejoin="round"
          className="w-[18px] h-[18px] absolute"
          style={{ color: "#f59e0b" }}
        >
          <circle cx="12" cy="12" r="5" />
          <line x1="12" y1="1" x2="12" y2="3" />
          <line x1="12" y1="21" x2="12" y2="23" />
          <line x1="4.22" y1="4.22" x2="5.64" y2="5.64" />
          <line x1="18.36" y1="18.36" x2="19.78" y2="19.78" />
          <line x1="1" y1="12" x2="3" y2="12" />
          <line x1="21" y1="12" x2="23" y2="12" />
          <line x1="4.22" y1="19.78" x2="5.64" y2="18.36" />
          <line x1="18.36" y1="5.64" x2="19.78" y2="4.22" />
        </svg>
      )}
    </button>
  );
};

export default ThemeToggle;
